"""Supervisor models, incident lifecycle states, gate outcomes, and dossiers."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator

from netcoop.models.enums import TowerId
from netcoop.models.findings import Finding
from netcoop.models.hypotheses import Hypothesis
from netcoop.models.reports import FinalReport, TowerReport


def _ensure_utc(dt: datetime) -> datetime:
    if dt.tzinfo is None:
        raise ValueError("Datetime must be timezone-aware (UTC required).")
    return dt.astimezone(timezone.utc)


class IncidentLifecycleState(str, Enum):
    """Deterministic lifecycle state of an active incident investigation."""

    CREATED = "CREATED"
    TOWERS_RUNNING = "TOWERS_RUNNING"
    TOWERS_EVALUATED = "TOWERS_EVALUATED"
    SUPERVISOR_REASONING = "SUPERVISOR_REASONING"
    INVESTIGATING = "INVESTIGATING"
    PROPOSED = "PROPOSED"
    GATE_EVALUATING = "GATE_EVALUATING"
    PUBLISHED = "PUBLISHED"
    ABSTAINED = "ABSTAINED"
    FAILED = "FAILED"


class GateOutcome(str, Enum):
    """Possible outcomes of the independent Evidence and Release Gate."""

    PASS = "PASS"
    PASS_WITH_LIMITATIONS = "PASS_WITH_LIMITATIONS"
    RETRY = "RETRY"
    ABSTAIN = "ABSTAIN"
    REJECT = "REJECT"


class ConflictType(str, Enum):
    """Taxonomy of inter-tower diagnostic disagreements."""

    OBSERVATION = "observation"
    ENTITY = "entity"
    TEMPORAL = "temporal"
    SEMANTIC = "semantic"
    DOMAIN_INTERPRETATION = "domain_interpretation"
    CAUSAL = "causal"
    RECOMMENDATION = "recommendation"


class ConflictItem(BaseModel):
    """A classified diagnostic conflict between tower findings or hypotheses."""

    model_config = ConfigDict(extra="forbid")

    conflict_type: ConflictType
    competing_towers: list[TowerId]
    competing_hypotheses: list[str]
    description: str
    recommended_discriminating_task: str | None = None
    recommended_assignee: TowerId | None = None
    disposition: str | None = None  # e.g., "resolved_by_topology", "unresolved_ambiguity"


class GateCheckResult(BaseModel):
    """Outcome of a single deterministic release gate check."""

    model_config = ConfigDict(extra="forbid")

    check_name: str
    passed: bool
    message: str
    severity: str = "error"  # "error" or "warning"


class GateIssue(BaseModel):
    """Stable, machine-actionable release-gate feedback for the supervisor."""

    model_config = ConfigDict(extra="forbid")

    code: str
    check_name: str
    message: str
    retryable: bool = False


class GateResult(BaseModel):
    """Comprehensive evaluation record generated by the EvidenceReleaseGate."""

    model_config = ConfigDict(extra="forbid")

    outcome: GateOutcome
    passed: bool
    checks: list[GateCheckResult] = Field(default_factory=list)
    issues: list[GateIssue] = Field(default_factory=list)
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    limitations: list[str] = Field(default_factory=list)
    certified_final_report: FinalReport | None = None
    evaluated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @field_validator("evaluated_at")
    @classmethod
    def validate_utc(cls, v: datetime) -> datetime:
        return _ensure_utc(v)


class InvestigationBudget(BaseModel):
    """Investigation limits and policy bounds enforced by SupervisorRuntime."""

    model_config = ConfigDict(extra="forbid")

    # Initial proposal, pre-gate task review, gate-feedback review, and one
    # post-task reconsideration are the maximum calls in the bounded flow.
    max_supervisor_calls: int = 4
    max_investigation_rounds: int = 2
    max_tasks: int = 6
    max_peer_queries_per_task: int = 2
    max_retries: int = 1
    task_timeout_seconds: float = 30.0


class IncidentDossier(BaseModel):
    """Compact structured incident context assembled by SupervisorRuntime for RCA reasoning."""

    model_config = ConfigDict(extra="forbid")

    incident_id: str
    symptom: str = ""
    time_window: dict[str, Any] | None = None
    affected_entities: list[str] = Field(default_factory=list)
    tower_reports: dict[TowerId, TowerReport] = Field(default_factory=dict)
    findings: list[Finding] = Field(default_factory=list)
    hypotheses: list[Hypothesis] = Field(default_factory=list)
    topology_summary: dict[str, Any] = Field(default_factory=dict)
    conflicts: list[ConflictItem] = Field(default_factory=list)
    investigation_round: int = 1
    task_history: list[dict[str, Any]] = Field(default_factory=list)
    gate_feedback: list[dict[str, Any]] = Field(default_factory=list)
    peer_query_history: list[dict[str, Any]] = Field(default_factory=list)
    available_capabilities: list[str] = Field(default_factory=list)
    data_quality_warnings: list[str] = Field(default_factory=list)
